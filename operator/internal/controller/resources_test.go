var update = flag.Bool("update", false, "rewrite testdata/rendered.yaml")

func sample() *platformv1alpha1.OmniAgentCluster {
	return &platformv1alpha1.OmniAgentCluster{
		ObjectMeta: metav1.ObjectMeta{Name: "omniagent", Namespace: "omniagent"},
		Spec: platformv1alpha1.OmniAgentClusterSpec{
			ControlPlane: platformv1alpha1.ControlPlaneSpec{Image: "ghcr.io/jchetan26/omniagent-controlplane:0.4.0", Replicas: 3},
			Gateway:      platformv1alpha1.GatewaySpec{DeploymentName: "omniagent-backend", Port: 8000},
			Autoscaling: platformv1alpha1.AutoscalingSpec{Mode: platformv1alpha1.AutoscalingHPA, MinReplicas: 1,
				MaxReplicas: 4, TargetCPUUtilization: 60, ScaleDownStabilizationSeconds: 60},
		},
	}
}

// TestRenderedManifests pins every object the operator creates for a sample
// resource in testdata/rendered.yaml, which `omni check` scans like any other
// manifest (go test ./internal/controller -run TestRenderedManifests -update).
func TestRenderedManifests(t *testing.T) {
	c := sample()
	objs := []runtime.Object{
		desiredControlPlane(c), desiredControlPlaneService(c),
		desiredGatewayEndpoints(c, map[string]string{"app.kubernetes.io/component": "backend"}),
		desiredPDB(c), desiredNetworkPolicy(c), desiredHPA(c),
	}
	kinds := []schema.GroupVersionKind{
		appsv1.SchemeGroupVersion.WithKind("Deployment"),
		{Version: "v1", Kind: "Service"}, {Version: "v1", Kind: "Service"},
		{Group: "policy", Version: "v1", Kind: "PodDisruptionBudget"},
		{Group: "networking.k8s.io", Version: "v1", Kind: "NetworkPolicy"},
		{Group: "autoscaling", Version: "v2", Kind: "HorizontalPodAutoscaler"},
	}
	var buf bytes.Buffer
	buf.WriteString("# GENERATED by TestRenderedManifests: the objects the operator creates for a sample OmniAgentCluster.\n")
	for i, o := range objs {
		o.GetObjectKind().SetGroupVersionKind(kinds[i])
		out, err := yaml.Marshal(o)
		if err != nil {
			t.Fatal(err)
		}
		buf.WriteString("---\n")
		buf.Write(bytes.ReplaceAll(out, []byte("  creationTimestamp: null\n"), nil))
	}
	const path = "testdata/rendered.yaml"
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with -update)", err)
	}
	if !bytes.Equal(want, buf.Bytes()) {
		t.Fatal("operator output changed: run go test ./internal/controller -run TestRenderedManifests -update")
	}
}

func TestControlPlaneIsHardened(t *testing.T) {
	d := desiredControlPlane(sample())
	pod := d.Spec.Template.Spec
	c := pod.Containers[0]
	switch {
	case !*pod.SecurityContext.RunAsNonRoot, *pod.SecurityContext.RunAsUser == 0:
		t.Fatal("must run as non-root")
	case !*c.SecurityContext.ReadOnlyRootFilesystem, *c.SecurityContext.AllowPrivilegeEscalation:
		t.Fatal("root filesystem must be read-only, no privilege escalation")
	case len(c.SecurityContext.Capabilities.Drop) != 1 || c.SecurityContext.Capabilities.Drop[0] != "ALL":
		t.Fatal("must drop all capabilities")
	case c.Resources.Limits.Cpu().IsZero() || c.Resources.Requests.Memory().IsZero():
		t.Fatal("needs requests and limits")
	case c.ReadinessProbe == nil || c.LivenessProbe == nil, *pod.AutomountServiceAccountToken:
		t.Fatal("needs probes and no service-account token")
	case d.Spec.Strategy.RollingUpdate.MaxUnavailable.IntValue() != 0:
		t.Fatal("rollouts must not take a node away before its replacement is ready")
	}
}
