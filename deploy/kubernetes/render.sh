#!/usr/bin/env bash
# Regenerate the plain manifests from the Helm chart (default values).
#   deploy/kubernetes/render.sh            -> deploy/kubernetes/manifests/omniagent.yaml       (defaults)
#                                          -> deploy/kubernetes/manifests/omniagent-full.yaml  (+ Triton, Kafka, Go ingestion)
# Apply without Helm:  kubectl create namespace omniagent && kubectl apply -n omniagent -f deploy/kubernetes/manifests/
# (Helm hooks become plain resources: the seed Job runs once on apply; the test Pod is excluded.)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
{
  echo "# GENERATED by deploy/kubernetes/render.sh from helm/omniagent - do not edit by hand."
  helm template omniagent "$here/helm/omniagent" --namespace omniagent --skip-tests
} > "$here/manifests/omniagent.yaml"
echo "wrote $here/manifests/omniagent.yaml"
{
  echo "# GENERATED by deploy/kubernetes/render.sh from helm/omniagent - do not edit by hand."
  echo "# Full stack: defaults plus Triton (baked-model image), Kafka (KRaft) and the Go ingestion pipeline."
  helm template omniagent "$here/helm/omniagent" --namespace omniagent --skip-tests \
    --set triton.enabled=true --set triton.image.repository=ghcr.io/jchetan26/omniagent-triton \
    --set triton.image.tag=0.4.0 --set kafka.enabled=true --set ingestion.enabled=true
} > "$here/manifests/omniagent-full.yaml"
echo "wrote $here/manifests/omniagent-full.yaml"
